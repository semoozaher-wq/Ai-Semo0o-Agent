/** Column bytes for a character; unknown characters fall back to '?'. */
export function glyphFor(char) {
  const code = typeof char === 'number' ? char : String(char).charCodeAt(0);
  const index = code - 32;
  const base = (index >= 0 && index < GLYPHS.length ? index : 63 - 32) * FONT_WIDTH;
  return GLYPHS.slice(base, base + FONT_WIDTH);
}

/**
 * Measure a single line of text.
 * @param {string} text
 * @param {{scale?:number, letterSpacing?:number}} [options]
 */
export function measureLine(text, { scale = 1, letterSpacing = 1 } = {}) {
  const chars = [...String(text)];
  if (!chars.length) return { width: 0, height: FONT_HEIGHT * scale };
  const advance = (FONT_WIDTH + letterSpacing) * scale;
  return { width: chars.length * advance - letterSpacing * scale, height: FONT_HEIGHT * scale };
}

/**
 * Measure a block of text (may contain newlines).
 * @returns {{width:number, height:number, lineHeight:number, lines:string[]}}
 */
export function measureText(text, { scale = 1, letterSpacing = 1, lineSpacing = 2 } = {}) {
  const lines = String(text ?? '').split('\n');
  const lineHeight = (FONT_HEIGHT + lineSpacing) * scale;
  let width = 0;
  for (const line of lines) width = Math.max(width, measureLine(line, { scale, letterSpacing }).width);
  return { width, height: lines.length * lineHeight - lineSpacing * scale, lineHeight, lines };
}

/**
 * Greedy word-wrap to a maximum pixel width. Long words are hard-broken.
 * @returns {string[]}
 */
export function wrapText(text, maxWidth, { scale = 1, letterSpacing = 1 } = {}) {
  const out = [];
  for (const paragraph of String(text ?? '').split('\n')) {
    const words = paragraph.split(/\s+/).filter(Boolean);
    if (!words.length) { out.push(''); continue; }
    let current = '';
    for (const word of words) {
      const candidate = current ? `${current} ${word}` : word;
      if (measureLine(candidate, { scale, letterSpacing }).width <= maxWidth) { current = candidate; continue; }
      if (current) out.push(current);
      if (measureLine(word, { scale, letterSpacing }).width <= maxWidth) { current = word; continue; }
      // Hard-break an over-long word character by character.
      let piece = '';
      for (const char of word) {
        if (measureLine(piece + char, { scale, letterSpacing }).width > maxWidth && piece) { out.push(piece); piece = char; }
        else piece += char;
      }
      current = piece;
    }
    if (current) out.push(current);
  }
  return out;
}

/**
 * Render a single glyph into an anti-aliased coverage mask of size
 * (cellW*scale) x (cellH*scale). Each value is 0..1. Sampling is done by area
 * coverage (subsamples x subsamples per output pixel) so scaled text has smooth
 * edges instead of hard blocks.
 * @returns {{width:number, height:number, coverage:Float32Array}}
 */
export function glyphCoverage(char, { scale = 1, subsamples = 3 } = {}) {
  const columns = glyphFor(char);
  const w = FONT_WIDTH * scale;
  const h = FONT_HEIGHT * scale;
  const coverage = new Float32Array(w * h);
  const samples = subsamples * subsamples;
  for (let py = 0; py < h; py += 1) {
    for (let px = 0; px < w; px += 1) {
      let hits = 0;
      for (let sy = 0; sy < subsamples; sy += 1) {
        const gy = Math.min(FONT_HEIGHT - 1, Math.floor(((py + (sy + 0.5) / subsamples) / h) * FONT_HEIGHT));
        for (let sx = 0; sx < subsamples; sx += 1) {
          const gx = Math.min(FONT_WIDTH - 1, Math.floor(((px + (sx + 0.5) / subsamples) / w) * FONT_WIDTH));
          if ((columns[gx] >> gy) & 1) hits += 1;
        }
      }
      coverage[py * w + px] = hits / samples;
    }
  }
  return { width: w, height: h, coverage };
}

/** True when the character has a visible glyph (used for kerning decisions). */
export function isPrintable(char) {
  const code = String(char).charCodeAt(0);
  return code >= 32 && code <= 126;
}
