/**
 * Scalable bitmap font for the Creation Kernel.
 *
 * A 5x7 glyph grid (the classic, public-domain terminal font shape) covering
 * printable ASCII. It is the kernel's only text primitive and is deliberately
 * dependency-free: captions, titles, lower-thirds and the storyboard contact
 * sheet all render through it, so the deterministic Local Studio can produce
 * legible typography with zero fonts installed.
 *
 * To avoid the "blocky" look of a naive integer scale, `glyphCoverage` renders a
 * glyph into an anti-aliased coverage mask by area-sampling the 5x7 cells; the
 * raster compositor then alpha-blends that mask, giving smooth edges at any
 * size. Measurement and word-wrap are exact and shared with the compositor, so
 * layout and drawing never disagree.
 */

