// Composition Bundle — a self-contained, portable delivery of a production.
//
// Produces a ZIP containing the timeline IR, brief, storyboard, bibles, critique
// and manifest, the rendered media (GIF + AVI + optional PNG sequence + WAV),
// and a standalone HTML5 player so the result can be opened anywhere with no
// server and no dependencies.

import JSZip from 'jszip';
import { encodeWav } from '../media/media.mjs';
import { upmix } from '../media/audio.mjs';

function escapeHtml(text) {
  return String(text || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function playerHtml({ brief, storyboard, manifest, gifBase64, hasAvi }) {
  const scenes = (storyboard.scenes || [])
    .map((s) => `<li><strong>${escapeHtml(s.headline)}</strong><span>${escapeHtml(s.subhead)}</span><em>${s.duration}s · ${escapeHtml(s.camera)}</em></li>`)
    .join('\n');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(brief.title)} — Semo0o Studio</title>
<style>
  :root { --bg:${brief.paletteColors.background}; --accent:${brief.paletteColors.accent}; --text:${brief.paletteColors.text}; --muted:${brief.paletteColors.muted}; }
  * { box-sizing:border-box; }
  body { margin:0; background:var(--bg); color:var(--text); font:16px/1.5 system-ui,-apple-system,Segoe UI,Roboto,sans-serif; }
  header { padding:32px 24px; border-bottom:1px solid rgba(255,255,255,.08); }
  h1 { margin:0 0 6px; font-size:clamp(22px,4vw,40px); }
  .logline { color:var(--muted); max-width:60ch; }
  main { display:grid; gap:24px; grid-template-columns:minmax(0,1.6fr) minmax(280px,1fr); padding:24px; max-width:1200px; margin:0 auto; }
  @media (max-width:820px){ main{ grid-template-columns:1fr; } }
  .stage { background:#000; border-radius:14px; overflow:hidden; box-shadow:0 12px 40px rgba(0,0,0,.5); }
  .stage img { display:block; width:100%; height:auto; }
  .meta { display:flex; gap:16px; flex-wrap:wrap; color:var(--muted); font-size:14px; margin-top:12px; }
  .badge { background:rgba(255,255,255,.06); border:1px solid rgba(255,255,255,.1); padding:4px 10px; border-radius:999px; }
  ol { padding-left:0; list-style:none; margin:0; }
  ol li { padding:12px 14px; border:1px solid rgba(255,255,255,.08); border-radius:10px; margin-bottom:10px; display:grid; gap:2px; }
  ol li span { color:var(--muted); font-size:14px; }
  ol li em { color:var(--accent); font-size:12px; font-style:normal; letter-spacing:.04em; text-transform:uppercase; }
  a.dl { display:inline-block; margin-top:8px; color:var(--accent); text-decoration:none; border:1px solid var(--accent); padding:8px 14px; border-radius:10px; }
  footer { color:var(--muted); padding:24px; text-align:center; font-size:13px; }
</style>
</head>
<body>
<header>
  <h1>${escapeHtml(brief.title)}</h1>
  <p class="logline">${escapeHtml(brief.logline)}</p>
  <div class="meta">
    <span class="badge">${manifest.width}×${manifest.height}</span>
    <span class="badge">${manifest.fps} fps</span>
    <span class="badge">${manifest.duration}s</span>
    <span class="badge">${escapeHtml(brief.type)}</span>
    <span class="badge">${escapeHtml(brief.mood)}</span>
    ${manifest.hasAudio ? '<span class="badge">music</span>' : ''}
  </div>
</header>
<main>
  <section>
    <div class="stage">${gifBase64 ? `<img alt="rendered video" src="data:image/gif;base64,${gifBase64}" />` : '<p style="padding:24px">No preview available.</p>'}</div>
    ${hasAvi ? '<a class="dl" href="media/video.avi" download>Download video (AVI / MJPEG)</a>' : ''}
  </section>
  <aside>
    <h2 style="font-size:15px;letter-spacing:.08em;text-transform:uppercase;color:var(--muted)">Storyboard</h2>
    <ol>${scenes}</ol>
  </aside>
</main>
<footer>Generated by Semo0o Studio · one goal → a finished video</footer>
</body>
</html>`;
}

/**
 * Build the ZIP bundle.
 * @param {object} input
 * @returns {Promise<Buffer>}
 */
export async function buildBundle(input) {
  const { brief, storyboard, bibles, timeline, critique, manifest, media = {} } = input;
  const zip = new JSZip();

  zip.file('timeline.json', JSON.stringify(timeline, null, 2));
  zip.file('brief.json', JSON.stringify(brief, null, 2));
  zip.file('storyboard.json', JSON.stringify(storyboard, null, 2));
  zip.file('bibles.json', JSON.stringify(bibles, null, 2));
  if (critique) zip.file('critique.json', JSON.stringify(critique, null, 2));
  zip.file('manifest.json', JSON.stringify(manifest, null, 2));

  const mediaDir = zip.folder('media');
  let gifBase64 = null;
  if (media.gif) {
    mediaDir.file('video.gif', media.gif);
    gifBase64 = media.gif.toString('base64');
  }
  if (media.avi) mediaDir.file('video.avi', media.avi);
  if (media.audio) {
    const stereo = upmix(media.audio, 2);
    mediaDir.file('audio.wav', encodeWav({ samples: stereo.data, sampleRate: stereo.sampleRate, channels: 2, bitsPerSample: 16 }));
  }
  if (Array.isArray(media.pngs) && media.pngs.length) {
    const framesDir = zip.folder('frames');
    for (const png of media.pngs) framesDir.file(png.name, png.buffer);
  }

  zip.file('player.html', playerHtml({ brief, storyboard, manifest, gifBase64, hasAvi: !!media.avi }));
  zip.file('README.md', [
    `# ${brief.title}`,
    '',
    brief.logline,
    '',
    `- Resolution: ${manifest.width}×${manifest.height} @ ${manifest.fps}fps`,
    `- Duration: ${manifest.duration}s (${manifest.frameCount} frames)`,
    `- Formats: ${manifest.formats.join(', ')}`,
    `- Audio: ${manifest.hasAudio ? 'procedural music bed' : 'none'}`,
    '',
    '## Files',
    '- `player.html` — standalone player (open in any browser).',
    '- `media/video.gif` — animated GIF.',
    '- `media/video.avi` — MJPEG video with PCM audio.',
    '- `timeline.json` — the versioned Timeline IR (re-renderable).',
    '- `brief.json`, `storyboard.json`, `bibles.json`, `critique.json` — the creative decisions.',
    '',
    'Generated by Semo0o Studio.',
  ].join('\n'));

  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE', compressionOptions: { level: 6 } });
}
