export const AGENTS_BY_ID: Record<string, AgentManifest> = AGENTS.reduce(
  (acc, agent) => {
    acc[agent.id] = agent;
    return acc;
  },
  {} as Record<string, AgentManifest>,
);

export function getAgent(id: string): AgentManifest | undefined {
  return AGENTS_BY_ID[id];
}

export function featuredAgents(): AgentManifest[] {
  return AGENTS.filter((a) => a.featured);
}

export function editorsChoiceAgents(): AgentManifest[] {
  return AGENTS.filter((a) => a.editorsChoice);
}

export function agentsByCategory(category: string): AgentManifest[] {
  if (category === 'all') return AGENTS;
  if (category === 'featured') return featuredAgents();
  return AGENTS.filter((a) => a.category === category);
}
