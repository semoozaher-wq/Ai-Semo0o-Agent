function review(
  id: string,
  author: string,
  rating: number,
  text: string,
  daysAgo: number,
  avatarColor: string,
  helpful = 0,
): AgentReview {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  return {
    id,
    author,
    rating,
    text,
    createdAt: date.toISOString(),
    avatarColor,
    helpful,
  };
}

